def primary_column(a2: str) -> str:
    a2 = a2.upper()
    if a2 in JP_ONLY:
        return "jp"
    if a2 in UK_LIKE:
        return "uk"
    if a2 in EU_LIKE:
        return "eu"
    if a2 in AMERICAS_US:
        return "us"
    # Default: mixed (try EU, US, UK, JP) for ambiguous / global retail
    return "mixed"


def note_for(a2: str, name: str) -> str:
    if a2 in NOTES:
        return NOTES[a2]
    col = primary_column(a2)
    if col == "mixed":
        return (
            f"{name}: retail imports may use US, UK, EU, or JP labels—type the size exactly as on your tag."
        )
    hint = {
        "us": "US sizing is typical on domestic retail; EU/JP may appear on imports.",
        "eu": "EU sizing is typical; UK/US may appear on imports.",
        "uk": "UK sizing is typical; EU/US may appear on imports.",
        "jp": "JP (cm) sizing is typical for shoes; EU/US on imports.",
    }[col]
    return f"{name}: {hint}"


def main():
    raw = json.loads((ROOT / "tool" / "countries_raw.json").read_text(encoding="utf-8"))
    entries = []
    for item in raw:
        a2 = item["cca2"]
        name = item["name"]["common"].replace('"', "'")
        col = primary_column(a2)
        note = note_for(a2, name).replace('"', "'")
        entries.append((a2, name, col, note))

    entries.sort(key=lambda x: x[1].lower())

    lines = [
        "// Generated by tool/generate_country_sizing.py — do not edit by hand.",
        "",
        "import 'size_input_column.dart';",
        "",
        "class CountrySizingEntry {",
        "  const CountrySizingEntry({",
        "    required this.alpha2,",
        "    required this.name,",
        "    required this.primaryColumn,",
        "    required this.note,",
        "  });",
        "",
        "  final String alpha2;",
        "  final String name;",
        "  final SizeInputColumn primaryColumn;",
        "  final String note;",
        "}",
        "",
        "/// All ISO-3166 countries from REST Countries + sizing hints.",
        "const List<CountrySizingEntry> kCountrySizingEntries = [",
    ]
    for a2, name, col, note in entries:
        lines.append(
            f"  CountrySizingEntry(alpha2: '{a2}', name: {json.dumps(name)}, primaryColumn: SizeInputColumn.{col}, note: {json.dumps(note)}),"
        )
    lines.append("];")
    lines.append("")
    lines.append("CountrySizingEntry? countrySizingEntryByAlpha2(String code) {")
    lines.append("  final u = code.toUpperCase();")
    lines.append("  for (final e in kCountrySizingEntries) {")
    lines.append("    if (e.alpha2 == u) return e;")
    lines.append("  }")
    lines.append("  return null;")
    lines.append("}")
    lines.append("")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(entries)} countries to {OUT_PATH}")


if __name__ == "__main__":
    main()
