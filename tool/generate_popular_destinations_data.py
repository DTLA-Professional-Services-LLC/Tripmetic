def dart_string(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def emit_city(city: str, country: str, lat: float, lng: float) -> str:
    return (
        f"      PopularDestinationCity(\n"
        f"        city: '{dart_string(city)}',\n"
        f"        country: '{dart_string(country)}',\n"
        f"        latitude: {lat},\n"
        f"        longitude: {lng},\n"
        f"      ),"
    )


def main() -> None:
    repo = Path(__file__).resolve().parent.parent
    out = repo / "lib/features/bucket_list/domain/popular_destinations_data.dart"

    lines = [
        "/// Curated popular cities grouped by continent for the bucket-list explorer.",
        "class PopularDestinationCity {",
        "  const PopularDestinationCity({",
        "    required this.city,",
        "    required this.country,",
        "    required this.latitude,",
        "    required this.longitude,",
        "  });",
        "",
        "  final String city;",
        "  final String country;",
        "  final double latitude;",
        "  final double longitude;",
        "}",
        "",
        "class PopularDestinationRegion {",
        "  const PopularDestinationRegion({",
        "    required this.id,",
        "    required this.name,",
        "    required this.cities,",
        "  });",
        "",
        "  final String id;",
        "  final String name;",
        "  final List<PopularDestinationCity> cities;",
        "}",
        "",
        "/// Fifty popular destinations per continent.",
        "const List<PopularDestinationRegion> kPopularDestinationRegions =",
        "    <PopularDestinationRegion>[",
    ]

    for rid, name, cities in REGIONS:
        assert len(cities) == 50, f"{name} has {len(cities)} cities, expected 50"
        sorted_cities = sorted(
            cities,
            key=lambda c: (c[1].casefold(), c[0].casefold()),
        )
        lines.append("  PopularDestinationRegion(")
        lines.append(f"    id: '{rid}',")
        lines.append(f"    name: '{name}',")
        lines.append("    cities: <PopularDestinationCity>[")
        for c in sorted_cities:
            lines.append(emit_city(*c))
        lines.append("    ],")
        lines.append("  ),")

    lines.append("];")
    lines.append("")

    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({sum(len(c[2]) for c in REGIONS)} cities)")


if __name__ == "__main__":
    main()
