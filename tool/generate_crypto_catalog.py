def main():
    out = Path(__file__).resolve().parent.parent / "lib" / "features" / "crypto" / "data" / "crypto_catalog.dart"
    lines = [
        "// Generated by tool/generate_crypto_catalog.py — mock USD/unit for offline demo.",
        "",
        "import 'crypto_asset.dart';",
        "",
        "/// All tradable symbols (includes USD and major + extended altcoins).",
        "final List<CryptoAsset> kCryptoCatalog = [",
    ]
    seen = set()
    for row in ROWS:
        row = row.strip()
        if not row:
            continue
        parts = row.split("|")
        if len(parts) != 3:
            raise SystemExit(f"Bad row: {row}")
        tid, name, usd = parts[0].strip(), parts[1].strip(), parts[2].strip()
        key = tid.upper()
        if key in seen:
            continue
        seen.add(key)
        lines.append(f"  CryptoAsset('{key}', {repr(name)}, {usd}),")
    lines.append("];")
    lines.append("")
    lines.append("/// Map for quick rate lookup (same as [CryptoAsset.usdPerUnit]).")
    lines.append("Map<String, double> cryptoRatesMap() {")
    lines.append("  final m = <String, double>{};")
    lines.append("  for (final a in kCryptoCatalog) {")
    lines.append("    m[a.id] = a.usdPerUnit;")
    lines.append("  }")
    lines.append("  return m;")
    lines.append("}")
    lines.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(seen)} assets to {out}")

if __name__ == '__main__':
    main()
