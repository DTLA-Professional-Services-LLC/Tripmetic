function buildArb(locale, translations) {
  const out = {};
  const keys = Object.keys(translations).filter((k) => k !== "@@locale");
  keys.sort();
  out["@@locale"] = locale;
  for (const k of keys) {
    out[k] = translations[k];
    const ph = placeholders[k];
    if (ph && ph.length) {
      out["@" + k] = {
        placeholders: Object.fromEntries(
          ph.map((p) => [p, { type: "String" }]),
        ),
      };
    }
  }
  return out;
}

