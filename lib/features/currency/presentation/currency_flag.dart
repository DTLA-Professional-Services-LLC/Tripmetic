/// Two regional-indicator symbols (Unicode flag emoji) for [iso2] (e.g. `"US"`).
String flagEmojiFromIso2(String iso2) {
  final u = iso2.toUpperCase();
  if (u.length != 2) return '';
  final a = u.codeUnitAt(0);
  final b = u.codeUnitAt(1);
  if (a < 0x41 || a > 0x5a || b < 0x41 || b > 0x5a) return '';
  const base = 0x1f1e6;
  return String.fromCharCodes([base + (a - 0x41), base + (b - 0x41)]);
}

/// Flag emoji for a fiat currency, or a neutral symbol if unknown.
String flagEmojiForCurrency(FiatCurrency fiat) {
  final cc = _kCurrencyToCountry[fiat.code];
  if (cc != null && cc.length == 2) {
    return flagEmojiFromIso2(cc);
  }
  return '💱';
}
