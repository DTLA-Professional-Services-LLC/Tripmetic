/// One row of equivalent sizes (mock data for demo).
class SizeRow {
  const SizeRow({
    required this.id,
    required this.label,
    required this.us,
    required this.uk,
    required this.eu,
    required this.jp,
    required this.cn,
    required this.br,
    required this.it,
    required this.au,
  });

  final String id;
  final String label;
  final String us;
  final String uk;
  final String eu;
  final String jp;
  final String cn;
  final String br;
  final String it;
  final String au;
}

/// Categories with conversion rows (waist, letter, or numeric by region).
enum SizeCategory {
  mensShoes,
  womensShoes,
  womensDresses,
  mensShirts,
  mensPants,
  womensPants,
  womensBlouses,
  mensTshirts,
  womensTshirts,

  /// Same waist rows as [mensPants]; tips explain Asian cm vs inch tags.
  mensJeansWaist,

  /// Inseam in inches (L) with typical cm for JP/CN tags.
  mensJeansInseam,

  /// Full US W×L (e.g. 38×32) with regional shorthand on one row.
  mensJeansCombo,
  belts,
}

