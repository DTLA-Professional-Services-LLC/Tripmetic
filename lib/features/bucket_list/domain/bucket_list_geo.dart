/// US-affiliated territories (Mapbox still highlights each territory polygon by name).
const Set<String> kUnitedStatesTerritoryCountryNames = <String>{
  'Puerto Rico',
  'Guam',
  'United States Virgin Islands',
  'American Samoa',
  'Northern Mariana Islands',
};

bool isUnitedStatesCountry(String country) => country == kCountryUnitedStates;

bool isUnitedStatesTerritoryCountry(String country) =>
    kUnitedStatesTerritoryCountryNames.contains(country.trim());

bool isEuropeanCountry(String country) => kEuropeanCountryNames.contains(country);

bool isAsianCountry(String country) => kAsianCountryNames.contains(country);

bool isAfricanCountry(String country) => kAfricanCountryNames.contains(country);

String? resolveUsStateKey(String raw) {
  final usStates = kStateProvinceByCountry[kCountryUnitedStates];
  if (usStates == null) return null;
  return usStates.contains(raw) ? raw : null;
}
