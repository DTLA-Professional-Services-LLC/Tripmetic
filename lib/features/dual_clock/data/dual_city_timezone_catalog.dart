/// Sorted presets for dropdowns (UTC first, then alphabetical by label).
List<DualCityPreset> get dualCityPresetsSorted {
  final pairs = kDualCityLabelsToTimezoneIds.entries.toList()
    ..sort((a, b) => a.key.compareTo(b.key));
  final utc = pairs.where((e) => e.key == 'UTC').toList();
  final rest = pairs.where((e) => e.key != 'UTC').toList();
  return [
    ...utc.map((e) => DualCityPreset(label: e.key, timezoneId: e.value)),
    ...rest.map((e) => DualCityPreset(label: e.key, timezoneId: e.value)),
  ];
}
